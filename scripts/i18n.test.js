import assert from 'node:assert/strict';
import fs from 'node:fs';
assert.ok(fs.existsSync('src/i18n.js'), 'missing isolated i18n implementation');
const {createI18n,LANGUAGE_STORAGE_KEY,SUPPORTED_LANGUAGES,languageFromLocale,getLanguageLocale}=await import('../src/i18n.js');
assert.deepEqual(SUPPORTED_LANGUAGES.map(l=>l.id),['ja','en','es','pt-BR','zh-Hans','fr','de','ko','ru','it','zh-Hant','id','tr','vi','th']);
assert.equal(languageFromLocale('zh-Hant-CN'),'zh-Hant');
assert.equal(languageFromLocale('zh_HK'),'zh-Hant');
assert.equal(languageFromLocale('zh-Hans-TW'),'zh-Hans');
assert.equal(languageFromLocale('pt-PT'),'pt-BR');
assert.equal(languageFromLocale('fr-CA'),'fr');
assert.equal(languageFromLocale('unsupported'),null);
assert.equal(getLanguageLocale('zh-Hans'),'zh-CN');
const data=new Map([[LANGUAGE_STORAGE_KEY,'ja']]);
const storage={getItem:k=>data.get(k),setItem:(k,v)=>data.set(k,v)};
const i=createI18n({storage,navigatorObject:{languages:['fr-FR']}});
assert.equal(i.getLanguage(),'ja','valid saved choice wins');
i.setLanguage('de');assert.equal(data.get(LANGUAGE_STORAGE_KEY),'de');
i.setLanguage('unsupported');assert.equal(i.getLanguage(),'de');
assert.equal(createI18n({storage:null,navigatorObject:{languages:['zz','ko-KR']}}).getLanguage(),'ko');
assert.equal(createI18n({storage:null,navigatorObject:{languages:['zz']}}).getLanguage(),'en');
assert.equal(createI18n({storage:null,navigatorObject:{}}).getLanguage(),'en');
const blocked={getItem(){throw Error('denied')},setItem(){throw Error('quota')}};
const b=createI18n({storage:blocked,navigatorObject:{language:'es'}});b.setLanguage('vi');assert.equal(b.getLanguage(),'vi');
const catalogs={ja:{greeting:'こんにちは {name}',result:'{score} 秒'},en:{greeting:'Hello {name}',result:'{score} seconds'}};
const x=createI18n({storage:null,navigatorObject:{language:'ja'},catalogs});
assert.equal(x.t('greeting',{name:'<script>{score}</script>'}),'こんにちは <script>{score}</script>','parameter is not re-interpolated');
assert.equal(x.t('result',{score:1.25}),'1.25 秒');
x.setLanguage('en');assert.equal(x.t('result',{score:1.25}),'1.25 seconds');
assert.throws(()=>x.t('unknown'),/Missing translation/);
assert.equal(LANGUAGE_STORAGE_KEY,'tomatoku.language.v1');
console.log('✓ i18n language IDs, saved selection, locale fallback and interpolation isolation');
const main=fs.readFileSync('src/main.js','utf8');
assert.doesNotMatch(main,/step\.label\s*===\s*["']スタート/,'display label must not drive countdown behavior');
assert.match(main,/#language-select/,'language picker is connected');
assert.match(main,/data|applyTranslations/,'static translations are applied');
assert.match(fs.readFileSync('src/styles.css','utf8'),/#language-select\s*\{[^}]*min-height:\s*44px/s,'language control must be comfortably tappable');
// Execute the actual UI key handler rather than a duplicate implementation.
const vm=await import('node:vm');
const keyBody=main.match(/input\.addEventListener\("keydown", \(event\) => \{([\s\S]*?)\n  \}\);/)?.[1];
assert.ok(keyBody,'name keyboard handler exists');
let starts=0;
const context={GAME_MODE:{OFFICIAL:'official'},startInFlight:false,onStart(){starts++;context.startInFlight=true;}};
vm.createContext(context);vm.runInContext('function handler(event){'+keyBody+'}',context);
context.handler({key:'Enter',isComposing:false,keyCode:229});assert.equal(starts,0,'Safari IME ending Enter cannot start');
context.handler({key:'Enter',isComposing:true,keyCode:13});assert.equal(starts,0,'composition cannot start');
context.handler({key:'a',isComposing:false,keyCode:65});assert.equal(starts,0);
context.handler({key:'Enter',isComposing:false,keyCode:13});assert.equal(starts,1,'ordinary Enter starts');
context.handler({key:'Enter',isComposing:false,keyCode:13});assert.equal(starts,1,'in-flight repeated Enter cannot start twice');
console.log('✓ Actual name key handler rejects IME 229/composition and repeated in-flight Enter');
